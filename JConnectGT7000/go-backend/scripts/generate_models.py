#!/usr/bin/env python3
"""Generate persistence structs only from the inspected live public schema; never change DB."""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
x=json.loads((root/'audit/database-schema.json').read_text())
def camel(value):return ''.join(s.title() for s in value.split('_'))
lines=['// Code generated by scripts/generate_models.py from the live schema. DO NOT EDIT.','package models','','import ("time"; "gorm.io/datatypes")','']
for t in x['tables']:
 name=t['table_name'];typ=camel(name);pk=[]
 for k in x['constraints']:
  if k['table_name']==name and k['contype']=='p':
   m=re.search(r'PRIMARY KEY \(([^)]+)\)',k['definition']);pk=m.group(1).replace('"','').split(', ') if m else []
 lines+=['// '+typ+' maps public.'+name+'.','type '+typ+' struct {']
 for c in x['columns']:
  if c['table_name']!=name:continue
  udt=c['udt_name'];gt={'int4':'int32','int8':'int64','bool':'bool','float8':'float64','numeric':'string','date':'time.Time','timestamp':'time.Time','timestamptz':'time.Time','jsonb':'datatypes.JSON','uuid':'string','text':'string','varchar':'string'}[udt]
  if c['is_nullable']=='YES' and udt!='jsonb':gt='*'+gt
  sqltype=udt
  if udt=='varchar' and c['character_maximum_length']:sqltype+=f"({c['character_maximum_length']})"
  if udt=='numeric' and c['numeric_precision'] is not None and c['numeric_scale'] is not None:sqltype+=f"({c['numeric_precision']},{c['numeric_scale']})"
  tag='column:'+c['column_name']+';type:'+sqltype
  if c['is_nullable']=='NO':tag+=';not null'
  if c['column_name'] in pk:tag+=';primaryKey;autoIncrement:'+('true' if str(c['column_default']).startswith('nextval(') else 'false')
  if c['column_name']=='created_at':tag+=';autoCreateTime:false'
  if c['column_name']=='updated_at':tag+=';autoUpdateTime:false'
  lines.append(f' {camel(c["column_name"])} {gt} `gorm:"{tag}" json:"-"`')
 for k in x['constraints']:
  if k['table_name']!=name or k['contype']!='f':continue
  m=re.match(r'FOREIGN KEY \(([^)]+)\) REFERENCES ([\w]+)\(([^)]+)\)',k['definition'])
  if not m:raise ValueError('Unrecognized FK: '+k['definition'])
  cols,ref,refcols=m.groups();fields=','.join(camel(v.strip()) for v in cols.split(','));refs=','.join(camel(v.strip()) for v in refcols.split(','))
  relation=camel(cols.replace(',','_'))+'Relation'
  lines.append(f' {relation} *{camel(ref)} `gorm:"foreignKey:{fields};references:{refs}" json:"-"`')
 lines+=['}',f'func ({typ}) TableName() string {{ return "public.{name}" }}','']
(root/'internal/models/schema.go').write_text('\n'.join(lines))
print(f'Generated {len(x["tables"])} models; associations only from verified foreign keys.')
